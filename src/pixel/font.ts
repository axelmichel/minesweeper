export const GLYPH_HEIGHT = 7;

export interface Glyph {
  rows: string[];
  width: number;
}

const cache = new Map<string, Glyph>();

/** The glyph for a character, trimmed to its lit columns unless `mono` keeps all five. */
export function glyph(ch: string, mono = false): Glyph {
  const key = mono ? `${ch}|m` : ch;
  const hit = cache.get(key);
  if (hit) return hit;
  let result: Glyph;
  const source = GLYPHS[ch];
  if (!source) {
    result = { rows: Array(GLYPH_HEIGHT).fill(''), width: 3 };
  } else {
    const rows = source.split(' ');
    let width = 5;
    if (!mono) {
      while (width > 1 && rows.every((r) => r[width - 1] === '.')) width--;
    }
    result = { rows: rows.map((r) => r.slice(0, width)), width };
  }
  cache.set(key, result);
  return result;
}
